#!/usr/bin/env python3
"""gen-tokens.py - gera os tokens do design system a partir do JSON fonte (T1-03).

Contrato
  Entrada : design/tokens/{colors,typography,spacing,radii,shadows}.json e design/motion/tokens.json
            (novos). Raiz: repositório (ou --root).
  Saída   : Packages/RackyKit/Sources/RackyDesignSystem/Tokens/
              Colors.generated.swift      DS.ColorSpec / DS.Color / DS.NS / DS.Terminal
              Typography.generated.swift  DS.Font (estilos) / DS.TerminalFont
              Space.generated.swift       DS.Space / DS.Layout
              Radius.generated.swift      DS.Radius
              Shadow.generated.swift      DS.Shadow
              MotionTokens.generated.swift  MotionTokens (duration, easing, spring, ...)
            design/motion/lib/tokens.js   window.MOTION e window.DS (protótipos HTML via file://)
            Determinístico (ordem do JSON, sem data); duas execuções geram os mesmos bytes.
  Modos   : sem flags grava os arquivos; --check não grava e sai com 1 se algum arquivo gerado
            está defasado ou ausente (CI).
  Exit    : 0 sucesso; 1 falha de validação/defasagem; 2 uso inválido.
Uso: scripts/gen-tokens.py [--check] [--root <dir>] [--help]
"""
import json
import os
import re
import sys

SWIFT_DIR = "Packages/RackyKit/Sources/RackyDesignSystem/Tokens"
JS_FILE = "design/motion/lib/tokens.js"
HEADER = (
    "// GENERATED by scripts/gen-tokens.py from {src}. DO NOT EDIT.\n"
    "// Regenerate: scripts/gen-tokens.py (CI: scripts/gen-tokens.py --check).\n"
)
SWIFT_KEYWORDS = {
    "default", "in", "is", "as", "do", "for", "if", "else", "repeat", "return", "switch", "case",
    "func", "init", "let", "var", "self", "super", "true", "false", "nil", "static", "struct",
    "class", "enum", "extension", "protocol", "import", "where", "while", "break", "continue",
    "operator", "subscript", "typealias", "throw", "try", "catch", "guard", "defer", "internal",
    "public", "private", "open", "inout", "Type", "Protocol",
}
IDENT = re.compile(r"^[a-z][A-Za-z0-9_]*$")
HEX = re.compile(r"^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$")


class Fail(Exception):
    pass


def fail(msg):
    raise Fail(msg)


def load(root, rel):
    path = os.path.join(root, rel)
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        fail("arquivo fonte ausente: %s" % rel)
    except json.JSONDecodeError as e:
        fail("JSON inválido em %s: %s" % (rel, e))


def ident(name, where):
    if not IDENT.match(name):
        fail("%s: nome inválido para identificador Swift: %r" % (where, name))
    return "`%s`" % name if name in SWIFT_KEYWORDS else name


def num(x, where):
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        fail("%s: número esperado, obtido %r" % (where, x))
    return x


def swift_num(x):
    if isinstance(x, int):
        return str(x)
    r = repr(float(x))
    return r


def swift_str(s):
    return json.dumps(s, ensure_ascii=False)


def parse_color(spec, where):
    """Retorna (rgb:int, alpha:float|None, alpha_byte:int|None, opacity:float|None)."""
    hx = spec["dark"] if isinstance(spec, dict) else spec
    if not isinstance(hx, str) or not HEX.match(hx):
        fail("%s: cor inválida %r (esperado #rrggbb ou #rrggbbaa)" % (where, hx))
    hx = hx[1:].lower()
    rgb = int(hx[:6], 16)
    byte = int(hx[6:], 16) if len(hx) == 8 else None
    op = spec.get("opacity") if isinstance(spec, dict) else None
    if op is not None:
        num(op, where + ".opacity")
        if not 0 < op < 1:
            fail("%s: opacity fora de (0,1): %r" % (where, op))
        if byte is not None:
            fail("%s: não combine #rrggbbaa com opacity" % where)
    return rgb, byte, op


def color_ctor(rgb, byte, op):
    if byte is not None:
        return "DSRGBA(hex: 0x%06x, alphaByte: 0x%02x)" % (rgb, byte)
    if op is not None:
        return "DSRGBA(hex: 0x%06x, opacity: %s)" % (rgb, swift_num(op))
    return "DSRGBA(hex: 0x%06x)" % rgb


def alpha_of(byte, op):
    if byte is not None:
        return byte / 255.0
    return float(op) if op is not None else 1.0


def dict_literal(pairs, indent="        "):
    if not pairs:
        return "[:]"
    lines = ["%s    %s: %s," % (indent, swift_str(k), v) for k, v in pairs]
    return "[\n" + "\n".join(lines) + "\n" + indent + "]"


# ---------------------------------------------------------------- cores
def collect_colors(doc):
    toks = []
    seen = set()
    if doc.get("schema") != "racky.tokens.colors":
        fail("colors.json: schema inesperado")
    for g in doc["groups"]:
        for name, spec in g["tokens"].items():
            where = "colors.%s.%s" % (g["name"], name)
            ident(name, where)
            if name in seen:
                fail("%s: nome duplicado" % where)
            seen.add(name)
            if "reference" not in spec:
                fail("%s: falta a chave 'reference' (variável de referência, 'palette:--color-*' ou null com 'note')" % where)
            if spec["reference"] is None and not spec.get("note"):
                fail("%s: reference=null exige 'note' justificando" % where)
            rgb, byte, op = parse_color(spec, where)
            if "light" in spec:
                parse_color(spec["light"], where + ".light")
            toks.append((name, g["name"], rgb, byte, op))
    return toks


def gen_colors(doc):
    toks = collect_colors(doc)
    term = doc["terminal"]
    out = [HEADER.format(src="design/tokens/colors.json"), "import AppKit\nimport SwiftUI\n\n",
           "extension DS {\n"]
    out.append("    /// Valores puros (testáveis). Alfa compõe sobre a superfície; nunca pré-misturar (02 §2).\n")
    out.append("    nonisolated public enum ColorSpec {\n")
    cur = None
    for name, grp, rgb, byte, op in toks:
        if grp != cur:
            out.append("        // %s\n" % grp)
            cur = grp
        out.append("        public static let %s = %s\n" % (name, color_ctor(rgb, byte, op)))
    out.append("\n        public static let all: [String: DSRGBA] = %s\n" %
               dict_literal([(n, n) for n, *_ in toks], "        "))
    out.append("    }\n\n")
    out.append("    /// SwiftUI.\n    nonisolated public enum Color {\n")
    for name, *_ in toks:
        out.append("        public static let %s = ColorSpec.%s.color\n" % (name, name))
    out.append("    }\n\n")
    out.append("    /// AppKit / SwiftTerm.\n    nonisolated public enum NS {\n")
    for name, *_ in toks:
        out.append("        public static var %s: AppKit.NSColor { ColorSpec.%s.nsColor }\n" % (name, name))
    out.append("    }\n\n")
    out.append("    /// Tema do terminal (02 §3).\n    nonisolated public enum Terminal {\n")
    for key in ("background", "foreground", "cursor", "cursorText", "selectionBackground"):
        rgb, byte, op = parse_color(term[key], "terminal." + key)
        out.append("        public static let %s = %s\n" % (key, color_ctor(rgb, byte, op)))
    ansi = term["ansi"]
    if len(ansi) != 16:
        fail("terminal.ansi deve ter 16 cores")
    out.append("        /// Índices 0-7 normais, 8-15 bright.\n        public static let ansi: [DSRGBA] = [\n")
    for i, hx in enumerate(ansi):
        rgb, byte, op = parse_color(hx, "terminal.ansi[%d]" % i)
        out.append("            %s,\n" % color_ctor(rgb, byte, op))
    out.append("        ]\n    }\n}\n")
    js = {}
    for name, grp, rgb, byte, op in toks:
        a = alpha_of(byte, op)
        r, g, b = (rgb >> 16) & 255, (rgb >> 8) & 255, rgb & 255
        css = "#%06x" % rgb if a == 1.0 else "rgba(%d, %d, %d, %s)" % (r, g, b, repr(round(a, 4)))
        js[name] = {"hex": "#%06x" % rgb, "alpha": a, "css": css}
    jterm = {}
    for key in ("background", "foreground", "cursor", "cursorText", "selectionBackground"):
        jterm[key] = "#%06x" % parse_color(term[key], key)[0]
    jterm["ansi"] = ["#%06x" % parse_color(h, "ansi")[0] for h in ansi]
    return "".join(out), {"color": js, "terminal": jterm}


# ---------------------------------------------------------------- tipografia
def gen_typography(doc):
    if doc.get("schema") != "racky.tokens.typography":
        fail("typography.json: schema inesperado")
    fams = doc["families"]
    for k in ("ui", "mono"):
        if k not in fams or "name" not in fams[k]:
            fail("typography.families.%s ausente" % k)
    out = [HEADER.format(src="design/tokens/typography.json"), "import CoreGraphics\n\n",
           "extension DS {\n    nonisolated public enum Font {\n"]
    out.append("        public static let uiFamilyName = %s\n" % swift_str(fams["ui"]["name"]))
    out.append("        public static let monoFamilyName = %s\n\n" % swift_str(fams["mono"]["name"]))
    names = []
    js = {}
    for name, s in doc["styles"].items():
        where = "typography.styles." + name
        ident(name, where)
        if s["family"] not in ("ui", "mono"):
            fail("%s: family deve ser ui ou mono" % where)
        for k in ("size", "weight", "lineHeight", "tracking"):
            num(s[k], where + "." + k)
        if not 100 <= s["weight"] <= 900:
            fail("%s: weight fora de 100-900" % where)
        tab = "true" if s.get("tabularDigits") else "false"
        out.append(
            "        public static let %s = DSTextStyle(name: %s, family: .%s, size: %s, weight: %s, lineHeight: %s, tracking: %s, tabularDigits: %s)\n"
            % (name, swift_str(name), s["family"], swift_num(s["size"]), swift_num(s["weight"]),
               swift_num(s["lineHeight"]), swift_num(s["tracking"]), tab))
        names.append((name, name))
        js[name] = {k: s[k] for k in ("family", "size", "weight", "lineHeight", "tracking")}
        js[name]["tabularDigits"] = bool(s.get("tabularDigits"))
    out.append("\n        public static let all: [String: DSTextStyle] = %s\n" % dict_literal(names, "        "))
    out.append("    }\n\n")
    t = doc["terminal"]
    out.append("    /// Fonte do terminal (02 §3): SF Mono, nunca Geist.\n    nonisolated public enum TerminalFont {\n")
    for k, ty in (("size", "CGFloat"), ("sizeMin", "CGFloat"), ("sizeMax", "CGFloat"), ("weight", "Double"),
                  ("boldWeight", "Double"), ("lineHeight", "CGFloat"), ("lineHeightMin", "CGFloat"),
                  ("lineHeightMax", "CGFloat"), ("padding", "CGFloat")):
        num(t[k], "terminal." + k)
        nm = "defaultSize" if k == "size" else k
        out.append("        public static let %s: %s = %s\n" % (nm, ty, swift_num(t[k])))
    out.append("    }\n}\n")
    jfonts = {"ui": fams["ui"]["name"], "mono": fams["mono"]["name"]}
    return "".join(out), {"font": {"families": jfonts, "styles": js}}


# ---------------------------------------------------------------- espaço, raios, sombras
def gen_scalar_enum(title, enum_name, entries, src, extra=None):
    out = [HEADER.format(src=src), "import CoreGraphics\n\n", "extension DS {\n"]
    out.append("    nonisolated public enum %s {\n" % enum_name)
    for name, v in entries:
        out.append("        public static let %s: CGFloat = %s\n" % (name, swift_num(v)))
    out.append("\n        public static let all: [String: CGFloat] = %s\n" %
               dict_literal([(n, n) for n, _ in entries], "        "))
    out.append("    }\n")
    return out


def entries_of(d, where):
    es = []
    for k, v in d.items():
        ident(k, where + "." + k)
        num(v, where + "." + k)
        es.append((k, v))
    return es


def gen_space(doc):
    if doc.get("schema") != "racky.tokens.spacing":
        fail("spacing.json: schema inesperado")
    sp = entries_of(doc["space"], "spacing.space")
    ly = entries_of(doc["layout"], "spacing.layout")
    out = gen_scalar_enum("space", "Space", sp, "design/tokens/spacing.json")
    out.append("\n    /// Constantes de layout (02 §5.2, §7, §10).\n    nonisolated public enum Layout {\n")
    for name, v in ly:
        out.append("        public static let %s: CGFloat = %s\n" % (name, swift_num(v)))
    out.append("\n        public static let all: [String: CGFloat] = %s\n" %
               dict_literal([(n, n) for n, _ in ly], "        "))
    out.append("    }\n}\n")
    return "".join(out), {"space": dict(sp), "layout": dict(ly)}


def gen_radii(doc):
    if doc.get("schema") != "racky.tokens.radii":
        fail("radii.json: schema inesperado")
    rs = entries_of(doc["radius"], "radii.radius")
    out = gen_scalar_enum("radius", "Radius", rs, "design/tokens/radii.json")
    num(doc["focusRingOutset"], "radii.focusRingOutset")
    out.insert(len(out), "")
    # focus ring outset dentro do enum Radius: reabre a extensão
    body = "".join(out)
    body = body.replace("\n        public static let all:", "\n        /// Raio do anel de foco = raio do controle + este valor (DS9).\n"
                        "        public static let focusRingOutset: CGFloat = %s\n\n        public static let all:" %
                        swift_num(doc["focusRingOutset"]), 1)
    body += "}\n"
    return body, {"radius": dict(rs), "focusRingOutset": doc["focusRingOutset"]}


def gen_shadows(doc):
    if doc.get("schema") != "racky.tokens.shadows":
        fail("shadows.json: schema inesperado")
    out = [HEADER.format(src="design/tokens/shadows.json"), "extension DS {\n",
           "    nonisolated public enum Shadow {\n"]
    names = []
    js = {}
    for name, layers in doc["shadows"].items():
        ident(name, "shadows." + name)
        items = []
        jl = []
        for i, L in enumerate(layers):
            w = "shadows.%s[%d]" % (name, i)
            for k in ("x", "y", "blur", "opacity"):
                num(L[k], w + "." + k)
            rgb, byte, op = parse_color(L["color"], w + ".color")
            if byte is not None or op is not None:
                fail("%s: cor da camada é #rrggbb; alfa vai em 'opacity'" % w)
            inset = "true" if L.get("inset") else "false"
            items.append("DSShadowLayer(x: %s, y: %s, blur: %s, colorHex: 0x%06x, opacity: %s, inset: %s)" % (
                swift_num(L["x"]), swift_num(L["y"]), swift_num(L["blur"]), rgb, swift_num(L["opacity"]), inset))
            jl.append({"x": L["x"], "y": L["y"], "blur": L["blur"], "color": "#%06x" % rgb,
                       "opacity": L["opacity"], "inset": bool(L.get("inset"))})
        out.append("        public static let %s = DSShadow(layers: [\n" % name)
        for it in items:
            out.append("            %s,\n" % it)
        out.append("        ])\n")
        names.append((name, name))
        js[name] = jl
    out.append("\n        public static let all: [String: DSShadow] = %s\n" % dict_literal(names, "        "))
    out.append("    }\n}\n")
    return "".join(out), {"shadow": js}


# ---------------------------------------------------------------- motion
def flatten(obj, prefix, nums, strs):
    if isinstance(obj, bool):
        return
    if isinstance(obj, (int, float)):
        nums[prefix] = float(obj)
    elif isinstance(obj, str):
        strs[prefix] = obj
    elif isinstance(obj, dict):
        for k, v in obj.items():
            flatten(v, prefix + "." + k if prefix else k, nums, strs)
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            flatten(v, "%s.%d" % (prefix, i), nums, strs)


def as_rows(v, where):
    """Normaliza trilha de keyframe para [[Double]]."""
    if isinstance(v, list) and v and all(isinstance(x, list) for x in v):
        return [[float(num(y, where)) for y in x] for x in v]
    if isinstance(v, list):
        return [[float(num(y, where)) for y in v]]
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return [[float(v)]]
    fail("%s: lista esperada" % where)


def rows_literal(rows):
    return "[" + ", ".join("[" + ", ".join(swift_num(y) for y in r) + "]" for r in rows) + "]"


def gen_motion(doc):
    if doc.get("schema") != "racky.motion.tokens":
        fail("motion/tokens.json: schema inesperado")
    out = [HEADER.format(src="design/motion/tokens.json"), "import CoreGraphics\n\n",
           "nonisolated public enum MotionTokens {\n",
           "    public static let schemaVersion = %d\n\n" % doc["version"]]

    def simple(group, enum, ty="Double"):
        es = entries_of(doc[group], "motion." + group)
        out.append("    public enum %s {\n" % enum)
        for n, v in es:
            out.append("        public static let %s: %s = %s\n" % (ident(n, group), ty, swift_num(v)))
        out.append("\n        public static let all: [String: %s] = %s\n    }\n\n" %
                   (ty, dict_literal([(n, n) for n, _ in es], "        ")))

    simple("duration", "Duration")
    out.append("    public enum Easing {\n")
    es = []
    for n, p in doc["easing"].items():
        if len(p) != 4:
            fail("motion.easing.%s: 4 pontos esperados" % n)
        for x in p:
            num(x, "motion.easing." + n)
        out.append("        public static let %s = Bezier(%s)\n" % (ident(n, "easing"), ", ".join(swift_num(x) for x in p)))
        es.append((n, n))
    out.append("\n        public static let all: [String: Bezier] = %s\n    }\n\n" % dict_literal(es, "        "))
    out.append("    public enum Springs {\n")
    es = []
    for n, p in doc["spring"].items():
        out.append("        public static let %s = SpringSpec(response: %s, dampingFraction: %s)\n" % (
            ident(n, "spring"), swift_num(num(p["response"], n)), swift_num(num(p["dampingFraction"], n))))
        es.append((n, n))
    out.append("\n        public static let all: [String: SpringSpec] = %s\n    }\n\n" % dict_literal(es, "        "))
    for g, e in (("distance", "Distance"), ("scale", "Scale"), ("opacity", "Opacity"), ("stroke", "Stroke"),
                 ("stagger", "Stagger"), ("delay", "Delay")):
        simple(g, e)
    out.append("    public enum Loop {\n")
    es = []
    for n, p in doc["loop"].items():
        nums_, strs_ = {}, {}
        for k, v in p.items():
            if k in ("period", "fps", "phase"):
                continue
            if isinstance(v, str):
                strs_[k] = v
            else:
                nums_[k] = as_rows(v, "motion.loop.%s.%s" % (n, k))[0]
        numbers = ", ".join("%s: %s" % (swift_str(k), "[" + ", ".join(swift_num(x) for x in v) + "]")
                            for k, v in nums_.items())
        extras_s = ", ".join("%s: %s" % (swift_str(k), swift_str(v)) for k, v in strs_.items())
        out.append("        public static let %s = MotionLoop(period: %s, fps: %s, phase: %s, numbers: [%s], strings: [%s])\n" % (
            ident(n, "loop"), swift_num(num(p["period"], n)), swift_num(num(p["fps"], n)), swift_str(p["phase"]),
            numbers or ":", extras_s or ":"))
        es.append((n, n))
    out.append("\n        public static let all: [String: MotionLoop] = %s\n    }\n\n" % dict_literal(es, "        "))
    out.append("    public enum Keyframes {\n")
    es = []
    for n, p in doc["keyframes"].items():
        tracks = {}
        scalars = {}
        strs_ = {}
        for k, v in p.items():
            if k in ("duration", "easing", "spring"):
                continue
            if isinstance(v, str):
                strs_[k] = v
            elif isinstance(v, (int, float)) and not isinstance(v, bool):
                scalars[k] = float(v)
            else:
                tracks[k] = as_rows(v, "motion.keyframes.%s.%s" % (n, k))
        t_lit = ", ".join("%s: %s" % (swift_str(k), rows_literal(v)) for k, v in tracks.items()) or ":"
        s_lit = ", ".join("%s: %s" % (swift_str(k), swift_num(v)) for k, v in scalars.items()) or ":"
        dur = swift_num(num(p["duration"], n)) if "duration" in p else "nil"
        easing = swift_str(p["easing"]) if "easing" in p else "nil"
        spring = swift_str(p["spring"]) if "spring" in p else "nil"
        out.append("        public static let %s = MotionKeyframe(duration: %s, easing: %s, spring: %s, tracks: [%s], scalars: [%s])\n" % (
            ident(n, "keyframes"), dur, easing, spring, t_lit, s_lit))
        es.append((n, n))
    out.append("\n        public static let all: [String: MotionKeyframe] = %s\n    }\n\n" % dict_literal(es, "        "))
    simple("policy", "Policy")
    nums, strs = {}, {}
    flatten(doc, "", nums, strs)
    out.append("    /// Todas as folhas numéricas do JSON, com chave pontilhada (ex.: \"duration.press\", \"easing.standard.0\").\n")
    out.append("    /// Usada pelo teste de paridade JSON x Swift x tokens.js (04 §9.4, MA1).\n")
    out.append("    public static let flat: [String: Double] = %s\n\n" % dict_literal(
        [(k, swift_num(v)) for k, v in nums.items()], "    "))
    out.append("    public static let flatStrings: [String: String] = %s\n}\n" % dict_literal(
        [(k, swift_str(v)) for k, v in strs.items()], "    "))
    return "".join(out), doc


# ---------------------------------------------------------------- driver
def build(root):
    files = {}
    colors = load(root, "design/tokens/colors.json")
    typo = load(root, "design/tokens/typography.json")
    spacing = load(root, "design/tokens/spacing.json")
    radii = load(root, "design/tokens/radii.json")
    shadows = load(root, "design/tokens/shadows.json")
    motion = load(root, "design/motion/tokens.json")
    js_ds = {}
    for fname, fn, doc in (("Colors", gen_colors, colors), ("Typography", gen_typography, typo),
                           ("Space", gen_space, spacing), ("Radius", gen_radii, radii),
                           ("Shadow", gen_shadows, shadows)):
        text, j = fn(doc)
        files["%s/%s.generated.swift" % (SWIFT_DIR, fname)] = text
        js_ds.update(j)
    mtext, mdoc = gen_motion(motion)
    files["%s/MotionTokens.generated.swift" % SWIFT_DIR] = mtext
    js = ["// GENERATED by scripts/gen-tokens.py from design/motion/tokens.json and design/tokens/*.json. DO NOT EDIT.\n",
          "// Existe porque fetch() de file:// é bloqueado nos protótipos HTML (04 §3.1).\n",
          "window.MOTION = %s;\n" % json.dumps(mdoc, indent=2, ensure_ascii=False),
          "window.DS = %s;\n" % json.dumps(js_ds, indent=2, ensure_ascii=False)]
    files[JS_FILE] = "".join(js)
    return files


def main(argv):
    args = argv[1:]
    check = False
    root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    i = 0
    while i < len(args):
        a = args[i]
        if a in ("-h", "--help"):
            print(__doc__)
            return 0
        if a == "--check":
            check = True
        elif a == "--root" and i + 1 < len(args):
            i += 1
            root = os.path.abspath(args[i])
        else:
            print(__doc__, file=sys.stderr)
            print("ERRO: argumento desconhecido: %s" % a, file=sys.stderr)
            return 2
        i += 1
    try:
        files = build(root)
    except Fail as e:
        print("ERRO: %s" % e, file=sys.stderr)
        return 1
    stale = []
    for rel, text in files.items():
        path = os.path.join(root, rel)
        cur = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                cur = f.read()
        if cur != text:
            stale.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if check:
        if stale:
            for rel in stale:
                print("ERRO: defasado ou ausente: %s (rode scripts/gen-tokens.py)" % rel, file=sys.stderr)
            return 1
        print("gen-tokens: OK (%d arquivos em dia)" % len(files))
        return 0
    print("gen-tokens: %d arquivos (%d atualizados)" % (len(files), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
